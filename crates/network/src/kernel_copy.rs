//! Linux/Android payload transport. Disk syscalls stay on the blocking pool;
//! sockets remain nonblocking. Sending falls back at the exact offset.
//! The receive helper is test-only, for standalone kernel-copy regression tests.
#[cfg(test)]
use std::os::fd::FromRawFd;
use std::{
    fs::File,
    io::{self, Read, Write},
    os::fd::{AsFd, AsRawFd, OwnedFd},
    sync::{
        Arc,
        atomic::{AtomicBool, AtomicU64, Ordering},
    },
    time::{Duration, Instant},
};
use tokio::net::TcpStream;

const CHUNK: usize = 1024 * 1024;

#[derive(Clone, Copy, Debug)]
pub(super) enum Direction {
    Send,
    #[cfg(test)]
    Receive,
}

#[derive(Default)]
struct Shared {
    bytes: AtomicU64,
    cancelled: AtomicBool,
}
struct Cancel(Arc<Shared>);
impl Drop for Cancel {
    fn drop(&mut self) {
        self.0.cancelled.store(true, Ordering::Relaxed);
    }
}

/// sendfile has no MSG_NOSIGNAL flag. Block SIGPIPE only on this worker and
/// consume a signal generated by our call before restoring the previous mask.
/// In particular, do not change the Java process's global signal disposition.
struct SigpipeGuard {
    set: libc::sigset_t,
    previous: libc::sigset_t,
    drain: bool,
}
impl SigpipeGuard {
    fn new() -> io::Result<Self> {
        // SAFETY: all signal-set pointers are initialized, live stack storage.
        unsafe {
            let mut set = std::mem::zeroed();
            let mut previous = std::mem::zeroed();
            let mut pending = std::mem::zeroed();
            libc::sigemptyset(&mut set);
            libc::sigaddset(&mut set, libc::SIGPIPE);
            let error = libc::pthread_sigmask(libc::SIG_BLOCK, &set, &mut previous);
            if error != 0 {
                return Err(io::Error::from_raw_os_error(error));
            }
            let drain = libc::sigpending(&mut pending) == 0
                && libc::sigismember(&previous, libc::SIGPIPE) == 0
                && libc::sigismember(&pending, libc::SIGPIPE) == 0;
            Ok(Self {
                set,
                previous,
                drain,
            })
        }
    }
}
impl Drop for SigpipeGuard {
    fn drop(&mut self) {
        // SAFETY: restore the same thread's saved mask; a zero timeout never
        // waits for a future signal. Pre-existing pending signals are preserved.
        unsafe {
            if self.drain {
                let zero = libc::timespec {
                    tv_sec: 0,
                    tv_nsec: 0,
                };
                while libc::sigtimedwait(&self.set, std::ptr::null_mut(), &zero) < 0
                    && io::Error::last_os_error().kind() == io::ErrorKind::Interrupted
                {
                }
            }
            libc::pthread_sigmask(libc::SIG_SETMASK, &self.previous, std::ptr::null_mut());
        }
    }
}

struct Control {
    shared: Arc<Shared>,
    last: Instant,
    idle: Duration,
    kernel_bytes: u64,
    kernel_calls: u64,
    pipe_capacity: i32,
    #[cfg(test)]
    fallback_after: Option<u64>,
}
impl Control {
    fn check(&self) -> io::Result<()> {
        if self.shared.cancelled.load(Ordering::Relaxed) {
            return Err(io::Error::new(
                io::ErrorKind::Interrupted,
                "Transfer cancelled",
            ));
        }
        if self.last.elapsed() >= self.idle {
            return Err(io::Error::new(
                io::ErrorKind::TimedOut,
                "Transfer idle timeout",
            ));
        }
        Ok(())
    }
    fn advance(&mut self, count: usize) {
        self.shared.bytes.fetch_add(count as u64, Ordering::Relaxed);
        self.last = Instant::now();
    }
    fn bytes(&self) -> u64 {
        self.shared.bytes.load(Ordering::Relaxed)
    }
    fn force_fallback(&self) -> bool {
        #[cfg(test)]
        if self
            .fallback_after
            .is_some_and(|limit| self.kernel_bytes >= limit)
        {
            return true;
        }
        false
    }
    fn wait(&self, fd: i32, events: i16) -> io::Result<()> {
        loop {
            self.check()?;
            let ms = self
                .idle
                .saturating_sub(self.last.elapsed())
                .as_millis()
                .clamp(1, 100) as i32;
            let mut descriptor = libc::pollfd {
                fd,
                events,
                revents: 0,
            };
            // SAFETY: descriptor is live for the call; poll does not own fd.
            let result = unsafe { libc::poll(&mut descriptor, 1, ms) };
            if result > 0 {
                return self.check();
            }
            if result < 0 {
                let error = io::Error::last_os_error();
                if error.kind() != io::ErrorKind::Interrupted {
                    return Err(error);
                }
            }
        }
    }
}

fn unsupported(error: &io::Error) -> bool {
    matches!(
        error.raw_os_error(),
        Some(libc::EINVAL | libc::ENOSYS | libc::EOPNOTSUPP | libc::EXDEV | libc::EPERM)
    )
}

#[cfg(test)]
fn pipe() -> io::Result<(OwnedFd, OwnedFd)> {
    let mut fds = [-1; 2];
    // SAFETY: pipe2 writes exactly two descriptors. CLOEXEC prevents leaking
    // transport internals into child processes; each end has one Rust owner.
    if unsafe { libc::pipe2(fds.as_mut_ptr(), libc::O_CLOEXEC | libc::O_NONBLOCK) } < 0 {
        return Err(io::Error::last_os_error());
    }
    // Reduce pipe-to-file syscall frequency when the kernel's pipe-page quota
    // permits it. EPERM/resource limits simply keep the system default size.
    unsafe {
        libc::fcntl(
            fds[0],
            libc::F_SETPIPE_SZ,
            super::buffer_size() as libc::c_int,
        );
    }
    Ok(unsafe { (OwnedFd::from_raw_fd(fds[0]), OwnedFd::from_raw_fd(fds[1])) })
}

fn send(
    socket: &mut std::net::TcpStream,
    file: &mut File,
    total: u64,
    control: &mut Control,
    fast: bool,
) -> io::Result<()> {
    let _signals = fast.then(SigpipeGuard::new).transpose()?;
    if fast {
        while control.bytes() < total {
            control.check()?;
            if control.force_fallback() {
                break;
            }
            let count = (total - control.bytes()).min(CHUNK as u64) as usize;
            // SAFETY: both FDs are owned by this worker. A null offset advances
            // the file position by precisely the number successfully sent.
            let written = unsafe {
                libc::sendfile(
                    socket.as_raw_fd(),
                    file.as_raw_fd(),
                    std::ptr::null_mut(),
                    count,
                )
            };
            control.kernel_calls += 1;
            if written > 0 {
                control.advance(written as usize);
                control.kernel_bytes += written as u64;
            } else if written == 0 {
                return Err(io::Error::new(
                    io::ErrorKind::UnexpectedEof,
                    "Source file shortened during transfer",
                ));
            } else {
                let error = io::Error::last_os_error();
                match error.kind() {
                    io::ErrorKind::Interrupted => continue,
                    io::ErrorKind::WouldBlock => control.wait(socket.as_raw_fd(), libc::POLLOUT)?,
                    _ if unsupported(&error) => break,
                    _ => return Err(error),
                }
            }
        }
    }
    if control.bytes() == total {
        return Ok(());
    }
    let mut buffer = vec![0; super::buffer_size()];
    while control.bytes() < total {
        control.check()?;
        let limit = (total - control.bytes()).min(buffer.len() as u64) as usize;
        let count = match file.read(&mut buffer[..limit]) {
            Err(e) if e.kind() == io::ErrorKind::Interrupted => continue,
            value => value?,
        };
        if count == 0 {
            return Err(io::Error::new(
                io::ErrorKind::UnexpectedEof,
                "Source file shortened during transfer",
            ));
        }
        let mut offset = 0;
        while offset < count {
            control.check()?;
            match socket.write(&buffer[offset..count]) {
                Ok(0) => return Err(io::ErrorKind::WriteZero.into()),
                Ok(n) => {
                    offset += n;
                    control.advance(n);
                }
                Err(e) if e.kind() == io::ErrorKind::Interrupted => {}
                Err(e) if e.kind() == io::ErrorKind::WouldBlock => {
                    control.wait(socket.as_raw_fd(), libc::POLLOUT)?
                }
                Err(e) => return Err(e),
            }
        }
    }
    Ok(())
}

#[cfg(test)]
fn write_file(file: &mut File, data: &[u8], control: &mut Control) -> io::Result<()> {
    let mut offset = 0;
    while offset < data.len() {
        control.check()?;
        match file.write(&data[offset..]) {
            Ok(0) => return Err(io::ErrorKind::WriteZero.into()),
            Ok(n) => {
                offset += n;
                control.advance(n);
            }
            Err(e) if e.kind() == io::ErrorKind::Interrupted => {}
            Err(e) if e.kind() == io::ErrorKind::WouldBlock => {
                control.wait(file.as_raw_fd(), libc::POLLOUT)?
            }
            Err(e) => return Err(e),
        }
    }
    Ok(())
}

#[cfg(test)]
fn receive(
    socket: &mut std::net::TcpStream,
    file: &mut File,
    total: u64,
    control: &mut Control,
    fast: bool,
) -> io::Result<()> {
    // Pipe allocation is optional: resource limits can use the bounded buffer.
    if fast
        && total > 0
        && let Ok((read, write)) = pipe()
    {
        let mut input = File::from(read);
        // SAFETY: the descriptor is a live pipe owned by this worker.
        control.pipe_capacity = unsafe { libc::fcntl(input.as_raw_fd(), libc::F_GETPIPE_SZ) };
        'fast: while control.bytes() < total {
            control.check()?;
            let limit = (total - control.bytes()).min(CHUNK as u64) as usize;
            // SAFETY: descriptors are owned, offsets null for socket/pipe.
            let pulled = unsafe {
                libc::splice(
                    socket.as_raw_fd(),
                    std::ptr::null_mut(),
                    write.as_raw_fd(),
                    std::ptr::null_mut(),
                    limit,
                    libc::SPLICE_F_NONBLOCK,
                )
            };
            control.kernel_calls += 1;
            if pulled == 0 {
                return incomplete(total - control.bytes());
            }
            if pulled < 0 {
                let error = io::Error::last_os_error();
                match error.kind() {
                    io::ErrorKind::Interrupted => continue,
                    io::ErrorKind::WouldBlock => {
                        control.wait(socket.as_raw_fd(), libc::POLLIN)?;
                        continue;
                    }
                    _ if unsupported(&error) => break,
                    _ => return Err(error),
                }
            }
            let mut pending = pulled as usize;
            while pending > 0 {
                control.check()?;
                // SAFETY: only this worker accesses the pipe and file.
                let written = if control.force_fallback() {
                    -1
                } else {
                    unsafe {
                        libc::splice(
                            input.as_raw_fd(),
                            std::ptr::null_mut(),
                            file.as_raw_fd(),
                            std::ptr::null_mut(),
                            pending,
                            libc::SPLICE_F_NONBLOCK,
                        )
                    }
                };
                control.kernel_calls += 1;
                if written > 0 {
                    pending -= written as usize;
                    control.advance(written as usize);
                    control.kernel_bytes += written as u64;
                } else if written == 0 {
                    return Err(io::ErrorKind::WriteZero.into());
                } else {
                    let error = if control.force_fallback() {
                        io::Error::from_raw_os_error(libc::EINVAL)
                    } else {
                        io::Error::last_os_error()
                    };
                    match error.kind() {
                        io::ErrorKind::Interrupted => continue,
                        io::ErrorKind::WouldBlock => {
                            control.wait(file.as_raw_fd(), libc::POLLOUT)?
                        }
                        _ if unsupported(&error) => {
                            // Bytes already consumed from TCP must be drained
                            // before reading the socket with the buffered path.
                            let mut buffer = vec![0; super::buffer_size()];
                            while pending > 0 {
                                control.check()?;
                                let limit = pending.min(buffer.len());
                                let count = match input.read(&mut buffer[..limit]) {
                                    Err(e) if e.kind() == io::ErrorKind::Interrupted => {
                                        continue;
                                    }
                                    result => result?,
                                };
                                if count == 0 {
                                    return Err(io::ErrorKind::UnexpectedEof.into());
                                }
                                write_file(file, &buffer[..count], control)?;
                                pending -= count;
                            }
                            break 'fast;
                        }
                        _ => return Err(error),
                    }
                }
            }
        }
    }
    if control.bytes() == total {
        return Ok(());
    }
    let mut buffer = vec![0; super::buffer_size()];
    while control.bytes() < total {
        control.check()?;
        let limit = (total - control.bytes()).min(buffer.len() as u64) as usize;
        match socket.read(&mut buffer[..limit]) {
            Ok(0) => return incomplete(total - control.bytes()),
            Ok(count) => write_file(file, &buffer[..count], control)?,
            Err(e) if e.kind() == io::ErrorKind::Interrupted => {}
            Err(e) if e.kind() == io::ErrorKind::WouldBlock => {
                control.wait(socket.as_raw_fd(), libc::POLLIN)?
            }
            Err(e) => return Err(e),
        }
    }
    Ok(())
}

#[cfg(test)]
fn incomplete(remaining: u64) -> io::Result<()> {
    Err(io::Error::new(
        io::ErrorKind::UnexpectedEof,
        format!("Incomplete file: {remaining} bytes missing"),
    ))
}

pub(super) async fn copy(
    socket: &TcpStream,
    file: &tokio::fs::File,
    size: u64,
    direction: Direction,
    progress: impl FnMut(u64),
) -> anyhow::Result<()> {
    let socket = socket.as_fd().try_clone_to_owned()?;
    // try_clone waits for any Tokio file operation before handing off ownership.
    let file = file.try_clone().await?.into_std().await;
    let directional = match direction {
        Direction::Send => "PORTALO_DISABLE_SENDFILE",
        #[cfg(test)]
        Direction::Receive => "PORTALO_DISABLE_SPLICE",
    };
    let fast = std::env::var_os("PORTALO_DISABLE_ZERO_COPY").is_none()
        && std::env::var_os(directional).is_none();
    run(socket, file, size, direction, fast, super::IDLE, progress).await
}

async fn run(
    socket: OwnedFd,
    mut file: File,
    size: u64,
    direction: Direction,
    fast: bool,
    idle: Duration,
    mut progress: impl FnMut(u64),
) -> anyhow::Result<()> {
    let shared = Arc::new(Shared::default());
    let _cancel = Cancel(shared.clone());
    let worker = shared.clone();
    let mut task = tokio::task::spawn_blocking(move || {
        let mut control = Control {
            shared: worker,
            last: Instant::now(),
            idle,
            kernel_bytes: 0,
            kernel_calls: 0,
            pipe_capacity: 0,
            #[cfg(test)]
            fallback_after: None,
        };
        let mut socket = std::net::TcpStream::from(socket);
        let result = match direction {
            Direction::Send => send(&mut socket, &mut file, size, &mut control, fast),
            #[cfg(test)]
            Direction::Receive => receive(&mut socket, &mut file, size, &mut control, fast),
        };
        bevy::log::debug!(
            ?direction,
            kernel_bytes = control.kernel_bytes,
            kernel_calls = control.kernel_calls,
            pipe_capacity = control.pipe_capacity,
            bytes = control.bytes(),
            "Payload copy"
        );
        result
    });
    let mut tick = tokio::time::interval(Duration::from_millis(100));
    loop {
        tokio::select! {
            result = &mut task => {
                progress(shared.bytes.load(Ordering::Relaxed));
                return Ok(result??);
            }
            _ = tick.tick() => progress(shared.bytes.load(Ordering::Relaxed)),
        }
    }
}

